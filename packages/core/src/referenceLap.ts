/** Speed target (m/s) at a distance-from-line s, metres. */
export function refSpeedAt(s: number, lapLength: number): number {
  return refPedalAt(REF_LAP_SPEEDS, s, lapLength);
}

/** Generic per-bucket lookup with linear interpolation (wraps the lap). */
function refPedalAt(arr: number[], s: number, lapLength: number): number {
  const pos = ((s % lapLength) + lapLength) % lapLength;
  const f = pos / REF_BUCKET_METRES;
  const i0 = Math.floor(f) % arr.length;
  const i1 = (i0 + 1) % arr.length;
  const a = f - Math.floor(f);
  return arr[i0] * (1 - a) + arr[i1] * a;
}

/* TELEMETRY-V2: Chris's pedal traces. The AI brake model uses refBrakeAt to
   place its brake zones exactly where Chris braked (brk > 0.15), and
   refThrottleAt for corner-exit acceleration character. */
export function refBrakeAt(s: number, lapLength: number): number {
  return refPedalAt(REF_LAP_BRAKE, s, lapLength);
}

export function refThrottleAt(s: number, lapLength: number): number {
  return refPedalAt(REF_LAP_THROTTLE, s, lapLength);
}
